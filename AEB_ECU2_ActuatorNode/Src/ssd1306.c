//PB12 = RST (reset, activ pe 0: cat timp e 0, displayul sta resetat)
//PB14 = D/C (0 = ce trimitem e comanda, 1 = ce trimitem sunt date/pixeli)
//lista de comenzi de init (din datasheet SSD1306)
static const uint8_t init_cmds[] = {
	0xAE,        //display OFF cat timp il configuram
	0xD5, 0x80,
	0xA8, 0x3F,
	0xD3, 0x00,
	0x40,
	0x8D, 0x14,  //charge pump ON -> fara ea ecranul ramane negru
	0x20, 0x00,  //adresare orizontala -> la update trimitem 1024 octeti la rand
	0xA1,        //orientarea (A1 + C8): daca textul iese oglindit/cu capul in jos, de aici se schimba
	0xC8,
	0xDA, 0x12,
	0x81, 0xCF,  //contrastul
	0xD9, 0xF1,
	0xDB, 0x40,
	0xA4,        //TEST: toti pixelii aprinsi (dupa test -> 0xA4 = afiseaza ce e in buffer)
	0xA6,
	0x2E,
	0xAF         //display ON
};

//dimensiunile ecranului
#define SSD1306_WIDTH 128
#define SSD1306_HEIGHT 64

static void ssd1306_gpio_init(void) {
	//enable clock pt GPIOB
	RCC->AHB1ENR |= (1U<<1);
	//PB12 si PB14 ca output
	GPIOB->MODER &=~ (0x3U << 24);
	GPIOB->MODER |= (1U << 24);
	GPIOB->MODER &=~ (0x3U << 28);
	GPIOB->MODER |= (1U << 28);
	//pornim cu RST = 1 (displayul nu e tinut in reset), prin BSRR
	GPIOB->BSRR = (1U<<12);
}

static void ssd1306_write(const uint8_t *cmds, uint16_t n) {
	//D/C = 0 (urmeaza comenzi), prin BSRR
	GPIOB->BSRR = (1U<<30);
	//trimitem cei n octeti cu spi_transmit
	spi_transmit(cmds, n);
}

static void ssd1306_reset(void) {
	//RST = 0
	GPIOB->BSRR = (1U<<28);
	delay(1);
	//RST = 1
	GPIOB->BSRR = (1U<<12);
	delay(1);
}

void ssd1306_init(void) {
	ssd1306_gpio_init();
	ssd1306_reset();
	//trimitem toata lista de init
	ssd1306_write(init_cmds, sizeof(init_cmds));
}

