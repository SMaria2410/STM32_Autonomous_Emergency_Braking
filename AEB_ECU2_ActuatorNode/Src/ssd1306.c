static void ssd1306_write_data(const uint8_t *data, uint16_t n) {
	//la fel ca ssd1306_write, dar D/C = 1 (urmeaza date/pixeli)
	GPIOB->BSRR = (1U<<14);
	spi_transmit(data, n);
}

void ssd1306_clear(void) {
	//punem toti cei 1024 octeti din buffer pe 0
	//nu trimitem nimic la display, doar stergem copia
	for(int i = 0; i < 1024; i++) {
		buffer[i] = 0;
	}
}

void ssd1306_set_pixel(uint8_t x, uint8_t y, uint8_t on) {
	//daca x >= 128 sau y >= 64 -> return (ca sa nu scriem in afara bufferului)
	if(x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) {
		return;
	}
	//octetul: buffer[pagina * width + nr coloana], bitul din octet: nr liniei % 8
	//daca on -> set la bit, altfel -> clear la bit
	if(on == 0) {
		buffer[x + (y/8) * 128] &=~ (1U<<(y % 8));
	} else {
		buffer[x + (y/8) * 128] |= (1U<<(y % 8));
	}
}

void ssd1306_update(void) {
	//0x21, 0, 127 -> coloanele de la 0 la 127
	//0x22, 0, 7   -> paginile de la 0 la 7
	uint8_t addr_cmds[6] = {0x21, 0, 127, 0x22, 0, 7};
	ssd1306_write(addr_cmds, 6);
	//apoi trimitem tot bufferul (1024 de octeti) ca date
	ssd1306_write_data(buffer, 1024);
}

void ssd1306_draw_char(uint8_t x, uint8_t page, char c) {
	//daca pagina e out of bounds
	if(page >= 8) {
		return;
	}
	//ca sa nu citim in afara tabelului font5x7
	if(c < ' ' || c > '~') {
		c = '?';
	}
	//pt cele 5 coloane ale literei
	for(int i = 0; i < 5; i++) {
		//nu scriem in afara ecranului
		if(x + i >= 128) {
			return;
		}
		buffer[page * 128 + x + i] = font5x7[c - 32][i];
	}
	//coloana de dupa litera (x + 5) = 0 -> spatiul dintre litere
	if(x + 5 < 128) {
		buffer[page * 128 + x + 5] = 0;
	}
}

void ssd1306_draw_string(uint8_t x, uint8_t page, const char *str) {
	//cat timp caracterul curent nu e '\0' (ca la strlen):
	while(*str != 0) {
		ssd1306_draw_char(x, page, *str);
		x += 6; //(5 coloane litera + 1 spatiu)
		str++; // trecem la urmatorul caracter
	}
}

void ssd1306_draw_string_centered(uint8_t page, const char *str) {
	size_t n = strlen(str);
	uint8_t x;
	//  daca n * 6 > 128 -> textul nu incape, il incepem de la x = 0
	if(n * 6 > 128) {
		x = 0;
	}
	else {
		x = (128 - n * 6) / 2;
	}
	ssd1306_draw_string(x, page, str);
}
